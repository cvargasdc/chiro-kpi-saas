/**
 * Stored on `care_plans.payment_settings` and inside template
 * `default_selections.paymentSettings`.
 *
 * - `payInFull`: one-time amount after percent discount (Platinum).
 * - `monthlyPlan`: equal monthly payments after percent discount (Silver).
 * - `downPaymentPlan`: percent down + remaining / months (Gold).
 * - `planStartDate`: optional `YYYY-MM-DD` (UTC calendar).
 *
 * Percents are 0–100. Months are 1–120. Money in quotes is integer cents.
 */
export type CarePlanPaymentSettings = {
  payInFull: PayInFullSettings;
  monthlyPlan: MonthlyPlanSettings;
  downPaymentPlan: DownPaymentPlanSettings;
  planStartDate: string | null;
};

