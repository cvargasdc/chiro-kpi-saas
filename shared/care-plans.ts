/**
 * Care Plan Generator helpers.
 *
 * Subtotal is integer USD cents from the treatments catalog
 * (`quantity * treatments.priceCents`). Payment quotes are derived from that
 * subtotal. See docs/WEEK11-CARE-PLANS.md.
 *
 * Patient first/last name and notes are ePHI (encrypted at rest).
 */

import { centsToDollars } from "./kpis";

function formatPriceCents(cents: number): string {
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
  }).format(centsToDollars(cents));
}

