export function isCarePlanStatus(value: string): value is CarePlanStatus {
  return (CARE_PLAN_STATUSES as readonly string[]).includes(value);
}

export function percentOfCents(cents: number, percent: number): number {
  return Math.round((cents * percent) / 100);
}

function moneyFields(cents: number): { dollars: number; display: string } {
  return { dollars: centsToDollars(cents), display: formatPriceCents(cents) };
}

function clampInt(value: number, min: number, max: number): number {
  if (!Number.isFinite(value)) return min;
  return Math.min(max, Math.max(min, Math.round(value)));
}

function readNumber(raw: unknown): number | undefined {
  if (typeof raw === "number" && Number.isFinite(raw)) return raw;
  if (typeof raw === "string" && raw.trim() !== "") {
    const n = Number(raw);
    if (Number.isFinite(n)) return n;
  }
  return undefined;
}

function readBool(raw: unknown, fallback: boolean): boolean {
  if (typeof raw === "boolean") return raw;
  return fallback;
}

export function normalizeTreatmentSelections(
  raw: unknown,
):
  | { ok: true; selections: CarePlanTreatmentSelection[] }
  | { ok: false; error: string } {
  if (raw == null) {
    return { ok: true, selections: [] };
  }

  const collected: CarePlanTreatmentSelection[] = [];

  if (Array.isArray(raw)) {
    for (const item of raw) {
      if (!item || typeof item !== "object") {
        return { ok: false, error: "invalid_selections" };
      }
      const row = item as Record<string, unknown>;
      const treatmentId =
        typeof row.treatmentId === "string"
          ? row.treatmentId.trim()
          : typeof row.id === "string"
            ? row.id.trim()
            : "";
      if (!treatmentId) return { ok: false, error: "invalid_selections" };
      const quantity = readNumber(row.quantity) ?? 0;
      if (!Number.isInteger(quantity) || quantity < 0) {
        return { ok: false, error: "invalid_quantity" };
      }
      if (quantity === 0) continue;
      if (quantity > MAX_TREATMENT_QUANTITY) {
        return { ok: false, error: "quantity_too_large" };
      }
      const name = typeof row.name === "string" ? row.name.trim() : undefined;
      const unitPriceCents = readNumber(row.unitPriceCents);
      collected.push({
        treatmentId,
        quantity,
        ...(name ? { name } : {}),
        ...(unitPriceCents != null &&
        Number.isInteger(unitPriceCents) &&
        unitPriceCents >= 0
          ? { unitPriceCents }
          : {}),
      });
    }
  } else if (typeof raw === "object") {
    for (const [treatmentId, qtyRaw] of Object.entries(
      raw as Record<string, unknown>,
    )) {
      const id = treatmentId.trim();
      if (!id) continue;
      const quantity = readNumber(qtyRaw) ?? 0;
      if (!Number.isInteger(quantity) || quantity < 0) {
        return { ok: false, error: "invalid_quantity" };
      }
      if (quantity === 0) continue;
      if (quantity > MAX_TREATMENT_QUANTITY) {
        return { ok: false, error: "quantity_too_large" };
      }
      collected.push({ treatmentId: id, quantity });
    }
  } else {
    return { ok: false, error: "invalid_selections" };
  }

  const merged = new Map<string, CarePlanTreatmentSelection>();
  for (const row of collected) {
    const existing = merged.get(row.treatmentId);
    if (!existing) {
      merged.set(row.treatmentId, { ...row });
      continue;
    }
    const quantity = Math.min(
      MAX_TREATMENT_QUANTITY,
      existing.quantity + row.quantity,
    );
    merged.set(row.treatmentId, {
      ...existing,
      quantity,
      name: row.name ?? existing.name,
      unitPriceCents: row.unitPriceCents ?? existing.unitPriceCents,
    });
  }

  const selections = [...merged.values()];
  if (selections.length > MAX_SELECTIONS) {
    return { ok: false, error: "too_many_selections" };
  }
  return { ok: true, selections };
}

export function normalizePaymentSettings(
  raw: unknown,
):
  | { ok: true; settings: CarePlanPaymentSettings }
  | { ok: false; error: string } {
  const base: CarePlanPaymentSettings = {
    payInFull: { ...DEFAULT_PAYMENT_SETTINGS.payInFull },
    monthlyPlan: { ...DEFAULT_PAYMENT_SETTINGS.monthlyPlan },
    downPaymentPlan: { ...DEFAULT_PAYMENT_SETTINGS.downPaymentPlan },
    planStartDate: null,
  };
  if (raw == null) return { ok: true, settings: base };
  if (typeof raw !== "object") return { ok: false, error: "invalid_payment_settings" };
  const obj = raw as Record<string, unknown>;

  const pif = obj.payInFull;
  if (pif && typeof pif === "object") {
    const row = pif as Record<string, unknown>;
    const discount =
      readNumber(row.discountPercent) ?? readNumber(row.discount) ?? 10;
    if (discount < 0 || discount > MAX_DISCOUNT_PERCENT) {
      return { ok: false, error: "invalid_discount" };
    }
    base.payInFull = {
      enabled: readBool(row.enabled, true),
      discountPercent: clampInt(discount, 0, MAX_DISCOUNT_PERCENT),
    };
  }

  const monthly = obj.monthlyPlan;
  if (monthly && typeof monthly === "object") {
    const row = monthly as Record<string, unknown>;
    const discount =
      readNumber(row.discountPercent) ?? readNumber(row.discount) ?? 5;
    const months = readNumber(row.months) ?? 6;
    if (discount < 0 || discount > MAX_DISCOUNT_PERCENT) {
      return { ok: false, error: "invalid_discount" };
    }
    if (months < 1 || months > MAX_PLAN_MONTHS || !Number.isInteger(months)) {
      return { ok: false, error: "invalid_months" };
    }
    base.monthlyPlan = {
      enabled: readBool(row.enabled, true),
      discountPercent: clampInt(discount, 0, MAX_DISCOUNT_PERCENT),
      months,
    };
  }

  const down = obj.downPaymentPlan;
  if (down && typeof down === "object") {
    const row = down as Record<string, unknown>;
    const discount =
      readNumber(row.discountPercent) ?? readNumber(row.discount) ?? 7;
    const months = readNumber(row.months) ?? 4;
    const downPct =
      readNumber(row.downPaymentPercent) ??
      readNumber(row.downPaymentPercentage) ??
      30;
    if (discount < 0 || discount > MAX_DISCOUNT_PERCENT) {
      return { ok: false, error: "invalid_discount" };
    }
    if (months < 1 || months > MAX_PLAN_MONTHS || !Number.isInteger(months)) {
      return { ok: false, error: "invalid_months" };
    }
    if (downPct < 0 || downPct > MAX_DISCOUNT_PERCENT) {
      return { ok: false, error: "invalid_down_payment" };
    }
    base.downPaymentPlan = {
      enabled: readBool(row.enabled, true),
      discountPercent: clampInt(discount, 0, MAX_DISCOUNT_PERCENT),
      months,
      downPaymentPercent: clampInt(downPct, 0, MAX_DISCOUNT_PERCENT),
    };
  }

  if (obj.planStartDate === null || obj.planStartDate === "") {
    base.planStartDate = null;
  } else if (typeof obj.planStartDate === "string") {
    const value = obj.planStartDate.trim();
    if (value && !/^\d{4}-\d{2}-\d{2}$/.test(value)) {
      return { ok: false, error: "invalid_plan_start_date" };
    }
    base.planStartDate = value || null;
  }

  return { ok: true, settings: base };
}

export function snapshotSelections(
  selections: CarePlanTreatmentSelection[],
  catalog: TreatmentPriceLookup[],
):
  | { ok: true; selections: CarePlanTreatmentSelection[]; subtotalCents: number }
  | { ok: false; error: string; treatmentId?: string } {
  const byId = new Map(catalog.map((row) => [row.id, row]));
  const out: CarePlanTreatmentSelection[] = [];
  let subtotalCents = 0;
  for (const sel of selections) {
    const treatment = byId.get(sel.treatmentId);
    if (!treatment) {
      return { ok: false, error: "unknown_treatment", treatmentId: sel.treatmentId };
    }
    subtotalCents += treatment.priceCents * sel.quantity;
    out.push({
      treatmentId: sel.treatmentId,
      quantity: sel.quantity,
      name: treatment.name,
      unitPriceCents: treatment.priceCents,
    });
  }
  return { ok: true, selections: out, subtotalCents };
}

export function computeSubtotalCents(
  selections: CarePlanTreatmentSelection[],
  catalog: TreatmentPriceLookup[],
):
  | { ok: true; subtotalCents: number }
  | { ok: false; error: string; treatmentId?: string } {
  const snapped = snapshotSelections(selections, catalog);
  if (!snapped.ok) return snapped;
  return { ok: true, subtotalCents: snapped.subtotalCents };
}

export function buildLineItems(
  selections: CarePlanTreatmentSelection[],
  catalog: TreatmentPriceLookup[],
): { items: CarePlanLineItem[]; subtotalCents: number } {
  const byId = new Map(catalog.map((row) => [row.id, row]));
  const items: CarePlanLineItem[] = [];
  let subtotalCents = 0;
  for (const sel of selections) {
    const treatment = byId.get(sel.treatmentId);
    const unitPriceCents =
      treatment?.priceCents ??
      (typeof sel.unitPriceCents === "number" ? sel.unitPriceCents : 0);
    const name = treatment?.name ?? sel.name ?? "Removed service";
    const lineTotalCents = unitPriceCents * sel.quantity;
    subtotalCents += lineTotalCents;
    const unit = moneyFields(unitPriceCents);
    const line = moneyFields(lineTotalCents);
    items.push({
      treatmentId: sel.treatmentId,
      name,
      category: treatment?.category ?? null,
      quantity: sel.quantity,
      unitPriceCents,
      unitPrice: unit.dollars,
      unitPriceDisplay: unit.display,
      lineTotalCents,
      lineTotal: line.dollars,
      lineTotalDisplay: line.display,
      missingFromCatalog: !treatment,
    });
  }
  return { items, subtotalCents };
}

export function computePaymentQuotes(
  subtotalCents: number,
  settings: CarePlanPaymentSettings,
): CarePlanPaymentQuotes {
  const quotes: CarePlanPaymentQuotes = {
    payInFull: null,
    monthlyPlan: null,
    downPaymentPlan: null,
  };
  if (subtotalCents <= 0) return quotes;

  if (settings.payInFull.enabled) {
    const discountCents = percentOfCents(
      subtotalCents,
      settings.payInFull.discountPercent,
    );
    const totalCents = subtotalCents - discountCents;
    const total = moneyFields(totalCents);
    quotes.payInFull = {
      discountPercent: settings.payInFull.discountPercent,
      discountCents,
      totalCents,
      total: total.dollars,
      totalDisplay: total.display,
    };
  }

  if (settings.monthlyPlan.enabled) {
    const months = Math.max(1, settings.monthlyPlan.months);
    const discountCents = percentOfCents(
      subtotalCents,
      settings.monthlyPlan.discountPercent,
    );
    const totalCents = subtotalCents - discountCents;
    const monthlyPaymentCents = Math.round(totalCents / months);
    const total = moneyFields(totalCents);
    const monthly = moneyFields(monthlyPaymentCents);
    quotes.monthlyPlan = {
      discountPercent: settings.monthlyPlan.discountPercent,
      discountCents,
      totalCents,
      total: total.dollars,
      totalDisplay: total.display,
      months,
      monthlyPaymentCents,
      monthlyPayment: monthly.dollars,
      monthlyPaymentDisplay: monthly.display,
    };
  }

  if (settings.downPaymentPlan.enabled) {
    const months = Math.max(1, settings.downPaymentPlan.months);
    const discountCents = percentOfCents(
      subtotalCents,
      settings.downPaymentPlan.discountPercent,
    );
    const totalCents = subtotalCents - discountCents;
    const downPaymentCents = percentOfCents(
      totalCents,
      settings.downPaymentPlan.downPaymentPercent,
    );
    const remaining = totalCents - downPaymentCents;
    const monthlyPaymentCents = Math.round(remaining / months);
    const total = moneyFields(totalCents);
    const down = moneyFields(downPaymentCents);
    const monthly = moneyFields(monthlyPaymentCents);
    quotes.downPaymentPlan = {
      discountPercent: settings.downPaymentPlan.discountPercent,
      discountCents,
      totalCents,
      total: total.dollars,
      totalDisplay: total.display,
      downPaymentPercent: settings.downPaymentPlan.downPaymentPercent,
      downPaymentCents,
      downPayment: down.dollars,
      downPaymentDisplay: down.display,
      months,
      monthlyPaymentCents,
      monthlyPayment: monthly.dollars,
      monthlyPaymentDisplay: monthly.display,
    };
  }

  return quotes;
}

export function applyPracticeName(template: string, practiceName: string): string {
  return template.replaceAll("{practiceName}", practiceName);
}

export function addMonthsYmd(ymd: string, months: number): string | null {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(ymd)) return null;
  const [y, m, d] = ymd.split("-").map(Number);
  const dt = new Date(Date.UTC(y, m - 1 + months, d));
  const yy = dt.getUTCFullYear();
  const mm = String(dt.getUTCMonth() + 1).padStart(2, "0");
  const dd = String(dt.getUTCDate()).padStart(2, "0");
  return `${yy}-${mm}-${dd}`;
}
